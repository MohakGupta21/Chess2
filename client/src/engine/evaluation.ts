export function evaluateBoard(chess: Chess): number {
  let score = 0;
  const board = chess.board();
  for (let r = 0; r < 8; r++) {
    for (let f = 0; f < 8; f++) {
      const piece = board[r][f];
      if (!piece) continue;
      // chess.board()[0] is rank 8; convert to a1=0 index.
      const idx = (7 - r) * 8 + f;
      const base = PIECE_VALUE[piece.type];
      const pst = PST[piece.type];
      if (piece.color === "w") {
        score += base + pst[idx];
      } else {
        // Vertical flip only (idx ^ 56): mirror rank, keep file. Correct even
        // if a table is later made file-asymmetric.
        score -= base + pst[idx ^ 56];
      }
    }
  }
  return score;
}
